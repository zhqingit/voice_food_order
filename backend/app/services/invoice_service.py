"""Monthly invoices from the platform to stores.

An invoice bills the commission on completed orders that wasn't taken through
Stripe (orders paid at the store), the store's monthly fee, and any
adjustments the admin adds while reviewing the draft.

Each billed order is marked with the invoice (orders.invoice_id), so it is
never billed twice. Generating for a month picks up every unbilled completed
order placed that month or the month before (orders completed a few days
after the month closed are billed the next time).

Lifecycle:
  draft  generated by an admin; lines can be adjusted
         delete → gone, its orders become billable again
         void   → written off, its orders stay billed
  open   sent through Stripe Invoicing (emailed, Net 15)
         paid | uncollectible | void, via Stripe webhooks or admin actions
A month's total under MIN_TOTAL is not invoiced; its orders roll over.
"""
from __future__ import annotations

import uuid
from collections import defaultdict
from datetime import date
from decimal import Decimal

from sqlalchemy import func, select, update
from sqlalchemy.orm import Session

from app.core.errors import AppError
from app.core.time import utcnow_naive
from app.models.order import Order
from app.models.store import Store
from app.models.store_invoice import StoreInvoice, StoreInvoiceLine
from app.schemas.invoice import InvoiceDetailOut, InvoiceLineOut, InvoiceOut
from app.services import commission, order_payments, payment_service

ZERO = Decimal("0.00")
MIN_TOTAL = Decimal("1.00")  # smaller totals roll over to the next month
STRIPE_MIN_TOTAL = Decimal("0.50")
DAYS_UNTIL_DUE = 15

DRAFT, OPEN, PAID, VOID, UNCOLLECTIBLE = "draft", "open", "paid", "void", "uncollectible"


def month_label(period: date) -> str:
    return period.strftime("%B %Y")


def _shift_month(d: date, months: int) -> date:
    index = d.year * 12 + d.month - 1 + months
    return date(index // 12, index % 12 + 1, 1)


def _order_line(order: Order, collected_online: Decimal, amount: Decimal) -> StoreInvoiceLine:
    channel = "Phone" if commission.is_phone(order.channel) else "App"
    return StoreInvoiceLine(
        kind="order",
        description=f"{channel} order #{order.short_code} ({order.code_day:%b %d})",
        amount=amount,
        order_id=order.id,
        order_code=order.short_code,
        order_day=order.code_day,
        channel=order.channel,
        subtotal=order.subtotal - order.discount,  # what the commission was charged on
        commission_bps=order.commission_bps,
        commission=order.commission,
        collected_online=collected_online,
    )


def generate_drafts(db: Session, period: date) -> list[StoreInvoice]:
    """Create a draft for every store with something to bill for `period` and
    no live invoice for it yet. Safe to run again."""
    end = _shift_month(period, 1)
    already = set(
        db.execute(
            select(StoreInvoice.store_id).where(StoreInvoice.period == period).where(StoreInvoice.status != VOID)
        ).scalars()
    )

    orders = db.execute(
        select(Order)
        .where(Order.status == "completed")
        .where(Order.invoice_id.is_(None))
        .where(Order.code_day >= _shift_month(period, -1), Order.code_day < end)
        .order_by(Order.code_day, Order.created_at)
    ).scalars().all()
    collected = order_payments.commission_collected_by_order(db, [o.id for o in orders])
    billable: dict[uuid.UUID, list[tuple[Order, Decimal, Decimal]]] = defaultdict(list)
    for o in orders:
        online = min(max(collected.get(o.id, ZERO), ZERO), o.commission)
        if o.commission - online > 0:
            billable[o.store_id].append((o, online, o.commission - online))

    stores = db.execute(
        select(Store).where(Store.id.in_(list(billable)) | (Store.monthly_fee > 0)).order_by(Store.name)
    ).scalars().all()

    created: list[StoreInvoice] = []
    for store in stores:
        if store.id in already:
            continue
        lines = [_order_line(o, online, amount) for o, online, amount in billable.get(store.id, [])]
        if store.monthly_fee and store.monthly_fee > 0:
            lines.append(
                StoreInvoiceLine(kind="monthly_fee", description=f"Monthly fee, {month_label(period)}", amount=store.monthly_fee)
            )
        total = sum((line.amount for line in lines), ZERO)
        if total < MIN_TOTAL:
            continue
        invoice = StoreInvoice(id=uuid.uuid4(), store_id=store.id, period=period, status=DRAFT, total=total)
        db.add(invoice)
        db.flush()  # the invoice row must exist before lines and orders point at it
        for line in lines:
            line.invoice_id = invoice.id
            db.add(line)
        for o, _, _ in billable.get(store.id, []):
            o.invoice_id = invoice.id
        created.append(invoice)
    db.flush()
    return created


def lines(db: Session, invoice: StoreInvoice) -> list[StoreInvoiceLine]:
    return list(
        db.execute(
            select(StoreInvoiceLine)
            .where(StoreInvoiceLine.invoice_id == invoice.id)
            .order_by(StoreInvoiceLine.order_day.nulls_last(), StoreInvoiceLine.created_at)
        ).scalars()
    )


def _require(invoice: StoreInvoice, *statuses: str) -> None:
    if invoice.status not in statuses:
        raise AppError(409, "invoice_wrong_status", f"Not allowed on an invoice that is {invoice.status}.")


def _retotal(db: Session, invoice: StoreInvoice) -> None:
    db.flush()
    invoice.total = sum((line.amount for line in lines(db, invoice)), ZERO)


def add_adjustment(db: Session, invoice: StoreInvoice, *, description: str, amount: Decimal) -> None:
    _require(invoice, DRAFT)
    db.add(StoreInvoiceLine(invoice_id=invoice.id, kind="adjustment", description=description, amount=amount))
    _retotal(db, invoice)


def remove_adjustment(db: Session, invoice: StoreInvoice, line_id: uuid.UUID) -> None:
    _require(invoice, DRAFT)
    line = db.get(StoreInvoiceLine, line_id)
    if line is None or line.invoice_id != invoice.id or line.kind != "adjustment":
        raise AppError(404, "invoice_line_not_found", "Adjustment not found.")
    db.delete(line)
    _retotal(db, invoice)


def delete_draft(db: Session, invoice: StoreInvoice) -> None:
    """Throw a draft away; its orders will be billed by the next one generated."""
    _require(invoice, DRAFT)
    db.execute(update(Order).where(Order.invoice_id == invoice.id).values(invoice_id=None))
    db.delete(invoice)


def void(db: Session, invoice: StoreInvoice) -> None:
    """Write the invoice off. Its orders stay billed (never billed again)."""
    _require(invoice, DRAFT, OPEN, UNCOLLECTIBLE)
    if invoice.stripe_invoice_id:
        payment_service.void_invoice(invoice.stripe_invoice_id)
    invoice.status = VOID


def _stripe_lines(period: date, rows: list[StoreInvoiceLine]) -> list[tuple[str, Decimal]]:
    """The invoice as Stripe shows it: commission summed per channel (Stripe
    caps invoice lines; the order-by-order detail is in the store portal)."""
    out: list[tuple[str, Decimal]] = []
    for label, phone in (("app", False), ("phone", True)):
        orders = [r for r in rows if r.kind == "order" and commission.is_phone(r.channel or "") == phone]
        if orders:
            n = len(orders)
            out.append((
                f"Commission on {label} orders paid at the store, {month_label(period)} ({n} order{'s' if n != 1 else ''})",
                sum((r.amount for r in orders), ZERO),
            ))
    out += [(r.description, r.amount) for r in rows if r.kind != "order"]
    return out


def send(db: Session, invoice: StoreInvoice) -> None:
    _require(invoice, DRAFT)
    if invoice.total < STRIPE_MIN_TOTAL:
        raise AppError(409, "invoice_total_too_small", "Invoices under $0.50 can't be sent; void it instead.")
    store = db.get(Store, invoice.store_id)
    if not store.stripe_customer_id:
        store.stripe_customer_id = payment_service.ensure_customer(store)
        db.commit()  # keep the customer even if sending fails below
    sent = payment_service.send_invoice(
        customer_id=store.stripe_customer_id,
        invoice_ref=str(invoice.id),
        lines=_stripe_lines(invoice.period, lines(db, invoice)),
        description=f"VoxEats commission and fees for {month_label(invoice.period)}.",
        footer="Order-by-order details are in the VoxEats store portal under Billing.",
        days_until_due=DAYS_UNTIL_DUE,
    )
    invoice.status = OPEN
    invoice.stripe_invoice_id = sent.invoice_id
    invoice.hosted_url, invoice.pdf_url, invoice.due_date = sent.hosted_url, sent.pdf_url, sent.due_date
    invoice.sent_at = utcnow_naive()


def mark_paid_by_admin(db: Session, invoice: StoreInvoice) -> None:
    """Paid by check, cash or bank transfer outside Stripe."""
    _require(invoice, OPEN, UNCOLLECTIBLE)
    payment_service.mark_invoice_paid_out_of_band(invoice.stripe_invoice_id)
    _paid(invoice, out_of_band=True)


def _paid(invoice: StoreInvoice, *, out_of_band: bool, stripe_fee: Decimal | None = None) -> None:
    invoice.status = PAID
    invoice.paid_out_of_band = out_of_band
    invoice.stripe_fee = stripe_fee
    invoice.paid_at = utcnow_naive()


def is_overdue(invoice: StoreInvoice, today: date | None = None) -> bool:
    return invoice.status == OPEN and invoice.due_date is not None and invoice.due_date < (today or utcnow_naive().date())


def to_out(db: Session, invoices: list[StoreInvoice]) -> list[InvoiceOut]:
    ids = [i.id for i in invoices]
    counts = dict(
        db.execute(
            select(StoreInvoiceLine.invoice_id, func.count())
            .where(StoreInvoiceLine.invoice_id.in_(ids), StoreInvoiceLine.kind == "order")
            .group_by(StoreInvoiceLine.invoice_id)
        ).all()
    ) if ids else {}
    names = dict(
        db.execute(select(Store.id, Store.name).where(Store.id.in_({i.store_id for i in invoices}))).all()
    ) if ids else {}
    return [
        InvoiceOut(
            id=i.id,
            store_id=i.store_id,
            store_name=names.get(i.store_id, ""),
            period=i.period.strftime("%Y-%m"),
            status=i.status,
            overdue=is_overdue(i),
            total=i.total,
            order_count=counts.get(i.id, 0),
            due_date=i.due_date,
            hosted_url=i.hosted_url,
            pdf_url=i.pdf_url,
            paid_out_of_band=i.paid_out_of_band,
            sent_at=i.sent_at,
            paid_at=i.paid_at,
            created_at=i.created_at,
        )
        for i in invoices
    ]


def to_detail(db: Session, invoice: StoreInvoice) -> InvoiceDetailOut:
    [out] = to_out(db, [invoice])
    return InvoiceDetailOut(
        **out.model_dump(),
        lines=[InvoiceLineOut.model_validate(line, from_attributes=True) for line in lines(db, invoice)],
    )


CSV_HEADER = ["kind", "order", "day", "channel", "subtotal", "rate_%", "commission", "collected_online", "amount", "description"]


def csv_rows(detail: InvoiceDetailOut) -> list[list]:
    rows: list[list] = [CSV_HEADER]
    for line in detail.lines:
        rate = Decimal(line.commission_bps) / 100 if line.commission_bps is not None else None
        values = [
            line.kind, line.order_code, line.order_day, line.channel, line.subtotal,
            rate, line.commission, line.collected_online, line.amount, line.description,
        ]
        rows.append(["" if v is None else v for v in values])
    rows.append(["total", "", "", "", "", "", "", "", detail.total, ""])
    return rows


# ── Stripe webhooks ──────────────────────────────────────────────────────


def on_stripe_event(db: Session, *, event_type: str, stripe_invoice_id: str, paid_out_of_band: bool) -> None:
    invoice = db.execute(
        select(StoreInvoice).where(StoreInvoice.stripe_invoice_id == stripe_invoice_id).with_for_update()
    ).scalar_one_or_none()
    if invoice is None:
        return
    if event_type == "invoice.paid" and invoice.status != PAID:
        fee = None if paid_out_of_band else payment_service.fetch_invoice_stripe_fee(stripe_invoice_id)
        _paid(invoice, out_of_band=paid_out_of_band, stripe_fee=fee)
    elif event_type == "invoice.voided":
        invoice.status = VOID
    elif event_type == "invoice.marked_uncollectible" and invoice.status == OPEN:
        invoice.status = UNCOLLECTIBLE
